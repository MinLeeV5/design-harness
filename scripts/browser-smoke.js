// Convert an observed rectangle through the scaled iframe before a real mouse click.
async function clickProduct(host,owner,target,position) {
  await owner.scrollIntoViewIfNeeded();
  await target.evaluate(el=>{
    const r=el.getBoundingClientRect();
    window.scrollBy(0,r.top<0?r.top:r.bottom>innerHeight?r.bottom-innerHeight:0);
  });
  const local=await target.evaluate((el,pos)=>{
    const r=el.getBoundingClientRect();
    return {x:r.x+(pos?.x??r.width/2),y:r.y+(pos?.y??r.height/2),width:innerWidth,height:innerHeight};
  },position);
  const box=await owner.boundingBox();assert.ok(box);
  await host.mouse.click(box.x+local.x*box.width/local.width,box.y+local.y*box.height/local.height);
}
